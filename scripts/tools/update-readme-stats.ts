/**
 * `npm run readme` — rewrite the "Current content" table in README.md from the real validator counts.
 *
 *   npx tsx scripts/tools/update-readme-stats.ts [--check]
 *
 * The table used to be maintained by hand, which meant it was wrong within a day of being written.
 * This regenerates it, including the count of lesson bodies still missing — so the README states the
 * gap rather than implying the curriculum is finished.
 *
 * `--check` exits non-zero if the README is out of date instead of rewriting it, for use in CI.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateContent } from '../lib/content-validator.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const README = join(ROOT, 'README.md');
const START = '<!-- content-stats:start -->';
const END = '<!-- content-stats:end -->';

const { issues, counts } = validateContent();
const missingBodies = issues.filter((i) => i.message.includes('has no body file')).length;
const written = counts.lessons - missingBodies;
const n = (v: number) => v.toLocaleString('en-US');

/** Round to a readable figure so the table does not churn on every comma. */
const approxWords = `~${Math.round(counts.lessonWords / 1000)},000`;

const rows: [string, string][] = [
  ['Lesson bodies written', `${written} of ${counts.lessons} defined`],
  ['Lesson words', approxWords],
  ['Practice items', n(counts.items)],
  ['Interactive spreadsheets', n(counts.sheets)],
  ['Reference entries', n(counts.reference)],
  ['Code crosswalk tasks', n(counts.crosswalk)],
  ['MS Companion topics', n(counts.companion)],
  ['Case studies / capstones', `${counts.cases} / ${counts.capstones}`],
  ['Clinical documents', n(counts.documents)],
  ['Primary sources', n(counts.sources)],
  ['Datasets', n(counts.datasets)],
  ['Skills tracked', n(counts.skills)],
];

const table = ['| | Count |', '|---|---:|', ...rows.map(([k, v]) => `| ${k} | ${v} |`)].join('\n');

const gap =
  missingBodies === 0
    ? 'Every lesson defined in the curriculum has a body written.'
    : `**${missingBodies} lesson ${missingBodies === 1 ? 'body is' : 'bodies are'} still to be written.** ` +
      '`npm run validate` names each one, so the gap is always visible rather than hidden behind a ' +
      'placeholder page. Nothing in the app is stubbed: a lesson either exists in full, or the ' +
      'validator reports its absence.';

const block = [START, '', table, '', gap, '', `<sub>Regenerated by \`npm run readme\`.</sub>`, END].join('\n');

const src = readFileSync(README, 'utf8');
const s = src.indexOf(START);
const e = src.indexOf(END);
if (s < 0 || e < 0) {
  console.error(`README.md is missing the ${START} / ${END} markers around the content table.`);
  process.exit(1);
}
const next = src.slice(0, s) + block + src.slice(e + END.length);

if (process.argv.includes('--check')) {
  if (next !== src) {
    console.error('README.md content table is out of date — run `npm run readme`.');
    process.exit(1);
  }
  console.log('README.md content table is up to date.');
} else {
  writeFileSync(README, next);
  console.log(`README.md updated: ${written} of ${counts.lessons} lesson bodies, ${n(counts.items)} items.`);
}
